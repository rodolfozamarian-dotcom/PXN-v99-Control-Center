const DICTS: Record<Lang, Dict> = { pt, en, es };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? pt[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Função de tradução no idioma atual (re-renderiza ao trocar de idioma). */
export function useT(): TFn {
  const lang = useStore(settingsStore).lang;
  return (key, vars) => translate(lang, key, vars);
}
